// In-game stills of the nine historical battles for the loading screens and the history screen: desktop WebGPU at the
// highest level, no HUD, past the approach and in the thick of the fight, from a low camera beside the hottest pair of
// enemy ships.
//   node scripts/capture-battle-art.mjs --url=http://127.0.0.1:5312 --explore [--only=hansan,okpo] [--n=5] [--step=4] [--pre=0] [--turtle] [--out=shots/battle-art]
//     candidates: every --step real seconds at 32x, five framings of the fight at that moment, with a JSON of the poses
//     (--turtle frames only fights a turtle ship is in)
//   node scripts/capture-battle-art.mjs --url=http://127.0.0.1:5312 [--only=...] [--out=assets-src/battle-art-2026-10-15]
//     the chosen stills: runs each battle to the sim time recorded in PICKS and frames it with the recorded pose
//   node scripts/capture-battle-art.mjs --publish [--from=assets-src/battle-art-2026-10-15]
//     the kept stills to public/ui/art/loading_<id>.webp (1600x900) and loading_<id>_sm.webp (800x450), and the manifest
// The battle without player input is deterministic, so a sim time and a pose bring the same moment back; the smoke and
// sparks are not, so a rerun gives a sibling of the chosen frame, not the same pixels.
