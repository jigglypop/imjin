/** Runs the battle at 32x until the sim clock reaches `time`, the last seconds at 1x so the smoke is fresh. */
async function runTo(page, time) {
  await page.evaluate(() => { window.__engine.speed = 32; });
  while ((await page.evaluate(() => window.__engine.battle.time)) < time - 4) await page.waitForTimeout(100);
  await page.evaluate(() => { window.__engine.speed = 1; });
  while ((await page.evaluate(() => window.__engine.battle.time)) < time) await page.waitForTimeout(100);
}

/**
 * Framings of the fight now: the Joseon and Japanese ships closest to each other (recent hits, fires, a turtle ship and a
 * crowd around them count), seen side-on from both sides of the line between them, over the Joseon ship's shoulder and
 * over the Japanese ship's.
 */
function framings(page) {
  return page.evaluate((turtle) => {
    const e = window.__engine;
    const b = e.battle;
    const live = b.ships.filter((s) => s.alive && s.sinking <= 0);
    const sinking = b.ships.filter((s) => s.sinking > 0 && s.sinking < 0.8);
    const near = (x, z, r) => live.filter((o) => (o.x - x) ** 2 + (o.z - z) ** 2 < r * r).length + sinking.filter((o) => (o.x - x) ** 2 + (o.z - z) ** 2 < r * r).length * 3;
    let best = null;
    let bestScore = -Infinity;
    for (const s of live) {
      if (s.team !== 'joseon' || (turtle && s.spec.kind !== 'geobukseon')) continue;
      for (const t of live) {
        if (t.team === 'joseon') continue;
        const d = Math.hypot(t.x - s.x, t.z - s.z);
        if (d > (turtle ? 1500 : 900) || d < (turtle ? 15 : 40)) continue;
        const score = 600 - Math.abs(d - 220) * 0.8 + (b.time - s.lastHit < 8 ? 150 : 0) + (b.time - t.lastHit < 8 ? 150 : 0) + (t.fire > 0 ? 220 : 0) + (s.spec.kind === 'geobukseon' ? 160 : 0) + near((s.x + t.x) / 2, (s.z + t.z) / 2, 300) * 25;
        if (score > bestScore) {
          bestScore = score;
          best = { s, t, d };
        }
      }
    }
    if (!best) return [];
    const { s, t, d } = best;
    const mx = (s.x + t.x) / 2;
    const mz = (s.z + t.z) / 2;
    const line = Math.atan2(t.z - s.z, t.x - s.x);
    const dist = Math.max(150, d * 0.95);
    const r = (v) => Math.round(v * 100) / 100;
    // A low camera in a crowd ends up inside a hull: it backs off until no ship is within 50 m of it.
    const all = b.ships.filter((o) => o.alive || o.sinking > 0);
    const clear = (pose) => {
      for (let k = 0; k < 30; k += 1) {
        const dist = pose.distance + k * 20;
        const cx = pose.tx + Math.cos(pose.yaw) * Math.cos(pose.pitch) * dist;
        const cz = pose.tz + Math.sin(pose.yaw) * Math.cos(pose.pitch) * dist;
        if (!all.some((o) => (o.x - cx) ** 2 + (o.z - cz) ** 2 < 50 * 50)) return { ...pose, distance: Math.round(dist) };
      }
      return pose;
    };
    const behind = Math.atan2(s.z - t.z, s.x - t.x) + 0.32;
    return [
      { tag: 'side', pose: clear({ tx: r(mx), tz: r(mz), yaw: r(line + Math.PI / 2), pitch: 0.08, distance: Math.round(dist) }) },
      { tag: 'side-far', pose: clear({ tx: r(mx), tz: r(mz), yaw: r(line - Math.PI / 2), pitch: 0.08, distance: Math.round(dist) }) },
      { tag: 'shoulder-l', pose: clear({ tx: r(s.x + (t.x - s.x) * 0.45), tz: r(s.z + (t.z - s.z) * 0.45), yaw: r(behind), pitch: 0.06, distance: Math.round(d * 0.45 + 110) }) },
      { tag: 'shoulder-r', pose: clear({ tx: r(s.x + (t.x - s.x) * 0.45), tz: r(s.z + (t.z - s.z) * 0.45), yaw: r(behind - 0.64), pitch: 0.06, distance: Math.round(d * 0.45 + 110) }) },
      { tag: 'reverse', pose: clear({ tx: r(t.x + (s.x - t.x) * 0.45), tz: r(t.z + (s.z - t.z) * 0.45), yaw: r(line + 0.3), pitch: 0.07, distance: Math.round(d * 0.45 + 110) }) },
    ].map((f) => ({ ...f, time: Math.round(b.time), ship: s.name, kind: s.spec.kind, target: t.name, gap: Math.round(d) }));
  }, args.turtle === 'true');
}

async function frame(page, pose, path) {
  await page.evaluate((p) => {
    const e = window.__engine;
    e.rts.followId = 0;
    e.rts.cinematic = false;
    e.rts.setPose(p);
  }, pose);
  await page.waitForTimeout(Number(args.wait ?? 1800));
  await page.screenshot({ path, type: path.endsWith('.jpg') ? 'jpeg' : 'png', quality: path.endsWith('.jpg') ? 92 : undefined });
}

const provenance = [];
for (const id of only) {
  const url = `${base}/?scenario=${id}&hud=0&lv=4&q=high`;
  const page = await browser.newPage({ viewport: { width: W, height: H }, deviceScaleFactor: 1 });
  page.on('pageerror', (e) => console.log(`[${id}] pageerror ${e.message}`));
  await page.goto(url);
  await page.waitForFunction(() => window.__ready === true, null, { timeout: 300000 });
  await waitForContact(page, 180);
  if (explore) {
    const log = [];
    const n = Number(args.n ?? 5);
    const step = Number(args.step ?? 4);
    if (args.pre) {
      await page.evaluate(() => { window.__engine.speed = 32; });
      await page.waitForTimeout(Number(args.pre) * 1000);
    }
    for (let i = 0; i < n; i += 1) {
      await page.evaluate(() => { window.__engine.speed = 32; });
      await page.waitForTimeout(step * 1000);
      await page.evaluate(() => { window.__engine.speed = 1; });
      await page.waitForTimeout(2500);
      for (const f of await framings(page)) {
        const file = `${out}/${id}_${args.turtle === 'true' ? 't' : ''}${i}_${f.tag}.jpg`;
        await frame(page, f.pose, file);
        log.push({ file, ...f });
        console.log(id, i, f.tag, f.time, f.ship, '->', f.target, f.gap);
      }
    }
    writeFileSync(`${out}/${id}${args.turtle === 'true' ? '_turtle' : ''}.json`, JSON.stringify(log, null, 1));
  } else {
    const pick = PICKS[id];
    if (!pick) {
      console.log(id, 'has no pick');
      await page.close();
      continue;
    }
    await runTo(page, pick.time);
    const file = `${out}/${id}.jpg`;
    await frame(page, pick.pose, file);
    provenance.push({ scenario: id, file: file.split('/').pop(), url, pose: pick.pose, simTime: pick.time, viewport: [W, H], backend: 'webgpu (Edge, D3D11)', date: new Date().toISOString().slice(0, 10) });
    console.log('saved', file);
  }
  await page.close();
}
// A run of some battles keeps the record of the others.
if (!explore && provenance.length) {
  const path = `${out}/provenance.json`;
  let kept = [];
  try {
    kept = JSON.parse(readFileSync(path, 'utf8'));
  } catch {
    // first run into this folder
  }
  const merged = [...kept.filter((k) => !provenance.some((p) => p.scenario === k.scenario)), ...provenance];
  writeFileSync(path, JSON.stringify(merged, null, 1) + '\n');
}
await browser.close();
