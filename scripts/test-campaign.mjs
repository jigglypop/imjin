import { chromium } from 'playwright-core';
const browser = await chromium.launch({ channel: 'msedge', headless: true, args: ['--enable-unsafe-webgpu', '--enable-gpu', '--ignore-gpu-blocklist', '--use-angle=d3d11'] });
const page = await browser.newPage({ viewport: { width: 1600, height: 900 } });
const logs = [];
page.on('console', (m) => logs.push(`[${m.type()}] ${m.text()}`));
page.on('pageerror', (e) => logs.push(`[pageerror] ${e.message}`));
await page.goto('http://127.0.0.1:5291/');
await page.evaluate(() => localStorage.removeItem('imjin.campaign.v1'));
await page.reload();
await page.waitForSelector('.select-title', { timeout: 30000 });
await page.click('text=전역 · 1592');
await page.waitForTimeout(1500);
await page.click('text=군영 · 정비');
await page.waitForTimeout(800);
await page.screenshot({ path: 'shots/camp_panel.png' });
await page.click('.camp-head .mini-btn');
await page.waitForTimeout(400);
await page.screenshot({ path: 'shots/camp_select.png' });
await page.click('.select-foot .ink-btn');
await page.waitForFunction(() => window.__ready === true, null, { timeout: 120000 });
await page.waitForTimeout(3000);
const info = await page.evaluate(() => window.__info());
console.log('battle', JSON.stringify(info).slice(0, 200));
await page.screenshot({ path: 'shots/camp_battle.png' });
await page.evaluate(() => window.__engine.endBattle());
await page.waitForTimeout(1500);
await page.screenshot({ path: 'shots/camp_result.png' });
const camp = await page.evaluate(() => localStorage.getItem('imjin.campaign.v1'));
console.log('campaign', camp?.slice(0, 300));
console.log(logs.filter((l) => l.includes('error')).slice(-10).join('\n'));
await browser.close();
