// The numbered waves of a landing: "부산포 정박 3진", "사쓰마 7진" and the ships in them.
function waves(ko: string, en: string, first: number, last: number, ships: number) {
  for (let w = first; w <= last; w += 1) {
    EN_SIM[`${ko} ${w}진`] = `${en} ${w}`;
    for (let n = 1; n <= ships; n += 1) EN_SIM[`${ko} ${w}진 ${n}호`] = `${en} ${w} #${n}`;
  }
}
