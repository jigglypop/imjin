const MONTHS = ['Jan', 'Feb', 'Mar', 'Apr', 'May', 'Jun', 'Jul', 'Aug', 'Sep', 'Oct', 'Nov', 'Dec'];

/** The entries that follow from data: every date a turn can fall on, and each region's battle. */
function generated(): Record<string, string> {
  const out: Record<string, string> = {};
  // dateLabel() writes 'year년 month월'; the war runs from April 1592 for 36 seasons.
  for (let year = 1592; year <= 1602; year += 1) for (let month = 1; month <= 12; month += 1) out[`${year}년 ${month}월`] = `${MONTHS[month - 1]} ${year}`;
  for (const [ko, en] of Object.entries(REGION_NAMES)) out[`${ko} 해전`] = `Battle of ${en}`;
  return out;
}

